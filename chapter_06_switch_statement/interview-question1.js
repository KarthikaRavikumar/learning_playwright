//without break statement all the o/p will be printed
//with break only the selected case will be printed

let fruit = "banana";
switch (fruit) {
    case "apple":
        console.log("Apple selected");
        break;
    case "banana":
        console.log("Banana selected");
        break;
    case "cherry":
        console.log("Cherry selected");
        break;
    case "date":
        console.log("Date selected");
        break;
    default:
        console.log("Default reached");
}