/*for loop
helops you to repeat a block of code for a specific number of times

for (initialization; condition; increment/decrement) {
    // code to be executed
}
*/

//Pre Increment (++a)
let a = 10;
let b = ++a;
console.log(a);
console.log(b);

//Post Increment (a++)
let c = 10;
let d = c++;
console.log(c);
console.log(d);

